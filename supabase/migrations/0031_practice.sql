-- Practice: activities the student does on their own, between classes.
--
-- The mobile app's Practice tab has four skills — listening, speaking, reading
-- and writing — and each module has its own practice activities for each,
-- authored in the Studio's Practice tab and listed the way the course is:
-- Book One › Speaking › Practice 01.
--
--   practice_activities      one activity: its module, its skill, its document
--   practice_card_progress   where each card stands for each student, for the
--                            spaced repetition
--   student_practice_cards   the cards a student can practise right now
--   review_practice_card     the student's only way to write: one card, rated
--
-- Only speaking is played so far. Its document is a deck of cards:
--
--   { "cards": [{ "id", "prompt", "answer", "example"?, "lessonId"? }] }
--
--   prompt    what to say, in Portuguese — the front ("Sala de reunião")
--   answer    how it is said, in English — the back ("Meeting room")
--   example   the answer in a sentence ("Could you tell me where the meeting
--             room is?")
--   lessonId  the lesson it comes from. The student only gets a card once their
--             group has had that lesson's class — "everything comes from the
--             lessons you've already seen". A card without one is always out.
--
-- A card's `id` is generated by the Studio and never changes, for the same
-- reason a homework exercise has one: progress is kept by it, and keying it by
-- position would scramble every student's progress the first time a card is
-- moved.
--
-- The module is a real foreign key to `modules.id` — the first one: lessons
-- still name their module in free text (0003). An activity is filed under a
-- module rather than a lesson because it gathers cards from many lessons.
--
-- The spaced repetition is Leitner boxes. A card climbs a box each time it is
-- remembered and comes back after that box's interval; forgotten, it falls to
-- the bottom and comes back the same day. The intervals live in
-- `review_practice_card` below, and only there.
--
-- Run in the Supabase SQL editor (or `supabase db push`) after 0030, then deploy
-- the web app (the Studio's Practice tab) and the mobile app.
-- Idempotent — safe to re-run.

-- Activities -------------------------------------------------------------------

create table if not exists public.practice_activities (
  id          text primary key,
  module_id   uuid not null references public.modules (id) on delete cascade,
  skill       text not null check (skill in ('listening', 'speaking', 'reading', 'writing')),
  title       text not null default '',
  -- Its place among the module's activities for the same skill.
  position    integer not null default 0,
  status      text not null default 'draft' check (status in ('draft', 'published')),
  document    jsonb not null default '{}'::jsonb,
  created_by  uuid default auth.uid() references auth.users (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists practice_activities_module_skill_idx
  on public.practice_activities (module_id, skill, position);

drop trigger if exists practice_activities_set_updated_at on public.practice_activities;
create trigger practice_activities_set_updated_at
  before update on public.practice_activities
  for each row
  execute function public.set_updated_at();

-- The shared curriculum's rule (0006): any staff member, for everything.
alter table public.practice_activities enable row level security;

drop policy if exists "practice_activities_staff" on public.practice_activities;
create policy "practice_activities_staff"
  on public.practice_activities
  for all
  to authenticated
  using (public.is_staff())
  with check (public.is_staff());

-- Progress ---------------------------------------------------------------------
-- One row per card a student has practised. A card they have never seen has no
-- row: it is new, and due.
--
--   box          0–6, the Leitner box; the interval it comes back after
--   due_on       the day it comes back, in the school's time zone
--   last_rating  forgot | almost | remembered
--   last_score   how much of the answer speech recognition heard (0–1), for
--                the teacher; null when the student rated the card themselves

create table if not exists public.practice_card_progress (
  student_id   uuid not null references public.students (id) on delete cascade,
  activity_id  text not null references public.practice_activities (id) on delete cascade,
  card_id      text not null,
  box          smallint not null default 0 check (box between 0 and 6),
  due_on       date not null,
  last_rating  text check (last_rating in ('forgot', 'almost', 'remembered')),
  last_score   numeric(3, 2) check (last_score is null or (last_score >= 0 and last_score <= 1)),
  reviews      integer not null default 0,
  reviewed_at  timestamptz,
  primary key (student_id, activity_id, card_id)
);

-- A student's progress reaches whoever they belong to, like their submissions.
-- The student reads theirs through `student_practice_cards` and writes it
-- through `review_practice_card` — never the table.
alter table public.practice_card_progress enable row level security;

drop policy if exists "practice_card_progress_teacher" on public.practice_card_progress;
create policy "practice_card_progress_teacher"
  on public.practice_card_progress
  for select
  to authenticated
  using (public.owns_student(student_id));

-- The student's cards ----------------------------------------------------------
-- One row per card the student can practise: in a published activity of a
-- module they are working through, from a lesson their group has had (a class
-- somebody was present at — `student_classes.held`), or from no lesson at all.
-- With where they stand on it, when they have practised it before.
--
-- A student with no active group has no classes, so they get only the cards
-- without a lesson.
--
-- `with ordinality` keeps the deck's order: `card_position` is the card's place
-- in its activity, as the Studio lays it out.

drop view if exists public.student_practice_cards;
create view public.student_practice_cards as
  select
    a.id as activity_id,
    a.title as activity_title,
    a.skill,
    m.name as module,
    a.position,
    c.ord::integer as card_position,
    c.card ->> 'id' as card_id,
    c.card ->> 'prompt' as prompt,
    c.card ->> 'answer' as answer,
    nullif(trim(coalesce(c.card ->> 'example', '')), '') as example,
    nullif(c.card ->> 'lessonId', '') as lesson_id,
    l.title as lesson_title,
    p.box,
    p.due_on,
    coalesce(p.reviews, 0) as reviews
  from public.practice_activities a
  join public.modules m on m.id = a.module_id
  cross join lateral jsonb_array_elements(
    case when jsonb_typeof(a.document -> 'cards') = 'array' then a.document -> 'cards' else '[]'::jsonb end
  ) with ordinality as c(card, ord)
  left join public.lessons l on l.id = nullif(c.card ->> 'lessonId', '')
  left join public.practice_card_progress p
    on p.student_id = public.current_student_id()
   and p.activity_id = a.id
   and p.card_id = c.card ->> 'id'
  where a.status = 'published'
    and m.name in (select public.current_student_modules())
    and coalesce(c.card ->> 'id', '') <> ''
    and coalesce(c.card ->> 'prompt', '') <> ''
    and coalesce(c.card ->> 'answer', '') <> ''
    and (
      nullif(c.card ->> 'lessonId', '') is null
      or exists (
        select 1 from public.student_classes sc
        where sc.lesson_id = c.card ->> 'lessonId'
          and sc.held
      )
    );

revoke all on public.student_practice_cards from anon, authenticated;
grant select on public.student_practice_cards to authenticated;

-- Reviewing a card ---------------------------------------------------------------
-- The rating moves the card between boxes; the box sets when it comes back.
--
--   forgot      back to box 0, due today — it comes round again
--   almost      stays in its box (at least box 1), due tomorrow
--   remembered  up one box, due after that box's interval
--
-- Computed here rather than sent by the app, so the schedule is one rule
-- whatever version of the app is asking.

create or replace function public.review_practice_card(
  p_activity_id text,
  p_card_id text,
  p_rating text,
  p_score numeric default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  -- Days until a card in each box comes back: box 0 is today, box 6 a month on.
  v_intervals constant integer[] := array[0, 1, 2, 4, 8, 16, 32];
  v_student uuid;
  v_today date := (now() at time zone 'America/Sao_Paulo')::date;
  v_box smallint;
  v_due date;
begin
  v_student := public.current_student_id();
  if v_student is null then
    raise exception 'Only an active student can practise.' using errcode = '42501';
  end if;

  if p_rating not in ('forgot', 'almost', 'remembered') then
    raise exception 'Unknown rating: %', p_rating using errcode = '22023';
  end if;

  -- Reachability is the student's own view, as for homework (0005).
  if not exists (
    select 1 from public.student_practice_cards
    where activity_id = p_activity_id and card_id = p_card_id
  ) then
    raise exception 'That card is not available to you.' using errcode = '42501';
  end if;

  select box into v_box
  from public.practice_card_progress
  where student_id = v_student and activity_id = p_activity_id and card_id = p_card_id;

  v_box := coalesce(v_box, 0);

  if p_rating = 'forgot' then
    v_box := 0;
    v_due := v_today;
  elsif p_rating = 'almost' then
    v_box := greatest(v_box, 1);
    v_due := v_today + 1;
  else
    v_box := least(v_box + 1, 6);
    v_due := v_today + v_intervals[v_box + 1];
  end if;

  insert into public.practice_card_progress (
    student_id, activity_id, card_id, box, due_on, last_rating, last_score, reviews, reviewed_at
  )
  values (
    v_student, p_activity_id, p_card_id, v_box, v_due, p_rating,
    case when p_score is null then null else greatest(0, least(1, p_score)) end,
    1, now()
  )
  on conflict (student_id, activity_id, card_id)
  do update set
    box = excluded.box,
    due_on = excluded.due_on,
    last_rating = excluded.last_rating,
    last_score = excluded.last_score,
    reviews = public.practice_card_progress.reviews + 1,
    reviewed_at = excluded.reviewed_at;
end;
$$;

revoke all on function public.review_practice_card(text, text, text, numeric) from public, anon;
grant execute on function public.review_practice_card(text, text, text, numeric) to authenticated;
